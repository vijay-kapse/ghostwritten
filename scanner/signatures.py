"""Attribution rules, as data.

Every rule has an `id` (stored per commit, summed per month in `by_rule`). A rule fires when any of its
matchers fires. Matchers are deliberately narrow: a word appearing in prose never counts, only a trailer,
a tool-written footer, or an exact bot login does. When in doubt, a commit is not counted as AI.

Matcher kinds (all case-insensitive):
  trailer  regex searched in the value of each `Co-authored-by:` line ("Name <email>")
  body     regex searched in the full message, multiline (^ and $ match at line breaks)
  subject  regex searched in the first line of the message only
  logins   exact match against the author login, committer login, author name or committer name
  names    regex searched in the author name or committer name (git identity, not the GitHub login)

Regexes are written in the subset shared by Python `re` and JavaScript `RegExp` (no inline flags, no
named groups, no lookbehind), so `signatures.json` can be used as-is by the web with flags "im".

Run `python signatures.py` to regenerate `signatures.json`.
"""

