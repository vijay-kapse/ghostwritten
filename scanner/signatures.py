def match_rules(message: str, logins: list[str], names: list[str]) -> list[str]:
    """Return the ids of every rule that matches. `logins`/`names` hold author and committer values."""
    message = message or ""
    subject = message.split("\n", 1)[0]
    trailers = [m.group(1).strip() for m in _TRAILER_RE.finditer(message)]
    ids_lower = {x.lower() for x in logins + names if x}
    hits = []
    for r in _COMPILED:
        if (
            any(p.search(t) for p in r["trailer"] for t in trailers)
            or any(p.search(message) for p in r["body"])
            or any(p.search(subject) for p in r["subject"])
            or any(p.search(n) for p in r["names"] for n in names if n)
            or (r["logins"] & ids_lower)
        ):
            hits.append(r["id"])
    return hits


def is_automation(author_login: str | None, author_name: str | None) -> bool:
    for v in (author_login, author_name):
        if not v:
            continue
        v = v.lower()
        if v in _AUTOMATION:
            return True
    if UNLISTED_BOT_IS_AUTOMATION and author_login:
        lg = author_login.lower()
        if lg.endswith("[bot]") and lg not in _AGENT_BOTS:
            return True
    return False


def classify(commit: dict) -> tuple[str, list[str]]:
    """Classify one item from GET /repos/{o}/{r}/commits (or a compare response).

    Returns (category, rule_ids). Category is checked in this order and is exclusive:
      "merge"       2+ parents (excluded from the denominator)
      "automation"  author is a dependency/release/CI bot (excluded from both sides)
      "ai"          at least one rule matched (rule_ids lists all that matched)
      "human"       everything else
    """
    if len(commit.get("parents") or []) >= 2:
        return "merge", []
    c = commit.get("commit") or {}
    author_login = (commit.get("author") or {}).get("login")
    committer_login = (commit.get("committer") or {}).get("login")
    author_name = (c.get("author") or {}).get("name")
    committer_name = (c.get("committer") or {}).get("name")
    rules = match_rules(
        c.get("message") or "",
        [x for x in (author_login, committer_login) if x],
        [x for x in (author_name, committer_name) if x],
    )
    if is_automation(author_login, author_name):
        return "automation", []
    if rules:
        return "ai", rules
    return "human", []


def export() -> dict:
    return {
        "schema": SCHEMA,
        "version": VERSION,
        "flags": "im",
        "trailer_line": TRAILER_LINE,
        "order": ["merge", "automation", "ai", "human"],
        "notes": [
            "merge: commit has 2+ parents; excluded from the denominator.",
            "automation: author login or name is in `automation`, or the author login ends with [bot] and is "
            "not in `agent_bots`; excluded from numerator and denominator.",
            "ai: any rule matches. trailer patterns apply to the value of each line matching trailer_line; "
            "body to the whole message; subject to the first line; names to author/committer git names; "
            "logins are exact (lowercase) against author/committer login and git name.",
            "A commit can match several rules; by_rule counts each, so sum(by_rule) >= ai.",
        ],
        "automation": sorted(_AUTOMATION),
        "unlisted_bot_is_automation": UNLISTED_BOT_IS_AUTOMATION,
        "agent_bots": dict(sorted(AGENT_BOTS.items())),
        "rules": [
            {k: r[k] for k in ("id", "tool", "description", "trailer", "body", "subject", "names", "logins") if k in r}
            for r in RULES
        ],
    }


JSON_PATH = Path(__file__).with_name("signatures.json")


def write_json(path: Path = JSON_PATH) -> None:
    path.write_text(json.dumps(export(), indent=2) + "\n")


